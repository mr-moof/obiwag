class TestClassifyPrompt:
    """Only genuine user text gets grounded."""

    @pytest.mark.parametrize('prompt', [
        '<task-notification>\n<task-id>abc</task-id>',
        '<system-reminder>do the thing</system-reminder>',
        '<local-command-stdout>widgetapi output</local-command-stdout>',
    ])
    def test_machine_envelopes_are_skipped(self, prompt):
        """Matching keywords against
        machine plumbing would ground constantly and burn the dedupe budget."""
        assert ups.classify_prompt(prompt) == 'machine'

    def test_compaction_continuation_is_skipped(self):
        """A compaction summary names every technology touched all session, so it
        matches many patterns and describes the PAST task."""
        prompt = ('This session is being continued from a previous conversation '
                  'that ran out of context. We worked on WidgetAPI and PowerShell.')
        assert ups.classify_prompt(prompt) == 'continuation'

    @pytest.mark.parametrize('prompt', [
        '<Project><Reference Include="x"/></Project> why does this fail?',
        '<div>foo</div> — should this be a component?',
        'Caveat: The messages below were generated by the user while running '
        'local commands. C:\\> powershell.exe -File build.ps1',
        '/obi-auto fix the widgetapi mail script',
        'update the update set in dev',
    ])
    def test_legitimate_lookalikes_are_user_text(self, prompt):
        """A leading '<' is usually pasted XML/HTML/config — precisely the
        infrastructure text most likely to mention a grounded technology. And
        'Caveat:' envelopes wrap real user text."""
        assert ups.classify_prompt(prompt) == 'user'

    @pytest.mark.parametrize('prompt', ['', '   ', '\n\n'])
    def test_empty(self, prompt):
        assert ups.classify_prompt(prompt) == 'empty'


class TestInjection:
    def test_grounds_a_single_product_mention(self, timer):
        out = ups._handle({'prompt': "let's work on CanvasAPI",
                           'session_id': 's1'}, timer)
        ctx = out['hookSpecificOutput']['additionalContext']
        assert out['hookSpecificOutput']['hookEventName'] == 'UserPromptSubmit'
        # The banner names what was injected, not the session's task type -- they
        # differ once a higher-ranked topic has already been grounded.
        assert 'Grounding injected for: canvasapi' in ctx
        assert '[Grounding Sources Injected]' in ctx

    def test_output_is_json_serializable(self, timer):
        """Claude Code expects exactly one JSON object on stdout."""
        out = ups._handle({'prompt': 'widgetapi update set', 'session_id': 's1'}, timer)
        json.loads(json.dumps(out))

    def test_machine_prompt_injects_nothing(self, timer):
        assert ups._handle({'prompt': '<task-notification>x</task-notification>',
                            'session_id': 's1'}, timer) == {}

    def test_unmatched_prompt_injects_nothing(self, timer):
        assert ups._handle({'prompt': 'what is the weather like',
                            'session_id': 's1'}, timer) == {}

    def test_disabled_by_calibration(self, timer, monkeypatch):
        monkeypatch.setattr('core.calibration.is_safety_enabled', lambda name: False)
        assert ups._handle({'prompt': 'widgetapi update set',
                            'session_id': 's1'}, timer) == {}


class TestDedupe:
    def test_same_topic_grounds_once_per_session(self, timer):
        first = ups._handle({'prompt': 'widgetapi update set', 'session_id': 's1'}, timer)
        second = ups._handle({'prompt': 'another widgetapi business rule',
                              'session_id': 's1'}, timer)
        assert first != {}
        assert second == {}, 'a topic must not be re-injected in the same session'

    def test_a_different_topic_still_grounds(self, timer):
        ups._handle({'prompt': 'widgetapi update set', 'session_id': 's1'}, timer)
        out = ups._handle({'prompt': 'check the storagehost datastore', 'session_id': 's1'}, timer)
        assert 'storageapi' in out['hookSpecificOutput']['additionalContext']

    def test_a_new_session_grounds_again(self, timer):
        ups._handle({'prompt': 'widgetapi update set', 'session_id': 's1'}, timer)
        out = ups._handle({'prompt': 'widgetapi update set', 'session_id': 's2'}, timer)
        assert out != {}

    def test_only_claimed_topics_are_injected(self, timer):
        """If one topic was already claimed, the injected text must contain the
        fresh topic only -- not the one already grounded."""
        ups._handle({'prompt': 'widgetapi update set', 'session_id': 's1'}, timer)
        out = ups._handle({'prompt': 'widgetapi plus powershell pester',
                           'session_id': 's1'}, timer)
        ctx = out['hookSpecificOutput']['additionalContext']
        assert '[Pattern: powershell' in ctx
        assert '[Pattern: widgetapi' not in ctx

    # 'widgetapi update set and pester' ranks widgetapi FIRST (2 anchor hits:
    # widgetapi, update set) with powershell second (1: pester). Claiming
    # widgetapi on an earlier prompt then makes the top-ranked topic the stale
    # one and the fresh topic the lower-ranked one -- the case where the banner
    # and the injected block can disagree.
    _TOP_IS_STALE = 'widgetapi update set and pester'

    def test_banner_names_only_what_it_injected(self, timer):
        """The 'Detected task type' line must not announce a topic whose
        grounding is absent from the block below it."""
        ups._handle({'prompt': 'widgetapi update set', 'session_id': 's1'}, timer)
        out = ups._handle({'prompt': self._TOP_IS_STALE, 'session_id': 's1'}, timer)

        ctx = out['hookSpecificOutput']['additionalContext']
        banner = ctx.splitlines()[0]
        assert 'powershell' in banner, banner
        assert 'widgetapi' not in banner, (
            'banner named the stale top match, not what was injected'
        )
        assert '[Pattern: powershell' in ctx
        assert '[Pattern: widgetapi' not in ctx

    def test_session_task_type_is_the_top_match(self, timer):
        """task_type tracks the session's subject -- the top-ranked match, even
        when that topic was grounded earlier. Deliberately distinct from the
        banner, which names only what this prompt injected."""
        ups._handle({'prompt': 'widgetapi update set', 'session_id': 's1'}, timer)
        ups._handle({'prompt': self._TOP_IS_STALE, 'session_id': 's1'}, timer)
        assert SessionState('s1').get('task_type') == 'widgetapi'


