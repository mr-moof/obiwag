class TestLoggingSafety:
    """This hook sees EVERY prompt, so any logged excerpt becomes a standing
    on-disk record of user input -- which routinely contains credentials."""

    def test_prompt_text_is_never_logged(self, timer):
        secret = 'synthetic-' + 'Q' * 24
        ups._handle({'prompt': f'widgetapi update set {secret}',
                     'session_id': 's1'}, timer)

        assert secret not in timer.input_summary
        assert secret not in timer.output_summary
        assert 'kind=user' in timer.input_summary
        assert 'chars=' in timer.input_summary

    @pytest.mark.parametrize('mode', ['plain', 'non-string-prompt'])
    def test_secret_reaches_no_real_log_file(self, tmp_path, mode):
        """Run the REAL hook as a subprocess and grep the REAL logs.

        Asserting against a stub timer only proves the handler's intent; it says
        nothing about what run_hook actually persists.

        Neither case errors -- the non-string prompt is coerced rather than
        raising, which is the point of that fix. The genuine error path is
        covered separately below.
        """
        secret = 'synthetic-' + 'R' * 24
        payload = {'prompt': f'widgetapi update set {secret}',
                   'session_id': 'logsafety'}
        if mode == 'non-string-prompt':
            payload['prompt'] = {'nested': secret}

        env = dict(os.environ, OBI_ROOT=str(tmp_path), PYTHONIOENCODING='utf-8')
        proc = subprocess.run(
            [sys.executable, str(HOOKS_DIR / 'user_prompt_submit.py')],
            input=json.dumps(payload), capture_output=True, text=True,
            timeout=120, env=env, cwd=str(HOOKS_DIR),
        )
        assert proc.returncode == 0, proc.stderr

        obi = tmp_path / '.obi'
        scanned = []
        for name in ('hook-execution-log.jsonl', 'hook-errors.jsonl',
                     'swallowed-errors.jsonl'):
            p = obi / name
            if p.exists():
                scanned.append(name)
                assert secret not in p.read_text(encoding='utf-8'), (
                    f'{mode}: prompt text leaked into {name}'
                )
        assert scanned, 'no log files were written -- test proves nothing'

    def test_secret_absent_when_the_handler_actually_raises(self, tmp_path, monkeypatch):
        """The real error path: respond_with_error writes a record, and the
        prompt must not ride along in it."""
        import io

        from core.hook_runtime import run_hook

        monkeypatch.setenv('OBI_ROOT', str(tmp_path))
        secret = 'synthetic-' + 'S' * 24
        monkeypatch.setattr(
            sys, 'stdin',
            io.StringIO(json.dumps({'prompt': f'widgetapi {secret}',
                                    'session_id': 'errpath'})))

        def boom(input_data, timer):
            timer.set_input_summary('kind=user chars=42')
            raise RuntimeError('forced failure for the error path')

        with pytest.raises(SystemExit):
            run_hook('UserPromptSubmit', boom,
                     error_name='user_prompt_submit', fallback={})

        obi = tmp_path / '.obi'
        wrote_something = False
        for p in obi.rglob('*.jsonl'):
            wrote_something = True
            assert secret not in p.read_text(encoding='utf-8'), (
                f'prompt text leaked into {p.name} on the error path'
            )
        assert wrote_something, 'error path wrote no log -- test proves nothing'


